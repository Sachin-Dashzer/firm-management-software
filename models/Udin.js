// @ts-check

import mongoose from "mongoose";
import { softDeletePlugin } from "./plugins/softDelete.js";
import { auditPlugin } from "./plugins/audit.js";

/**
 * The UDIN register (P2-7).
 *
 * Spec section 16 requires a UDIN against every certificate, audit report and
 * attestation, and spec section 5 captures one when work is filed. Until now
 * that was a free-text field on the engagement: the same number could be
 * typed against two jobs, a certificate issued outside any engagement had
 * nowhere to live, and nobody could answer "what have we signed this year".
 *
 * A UDIN is generated on the ICAI's portal against **a member**, not a firm,
 * so the member is recorded and their membership number is snapshotted — the
 * register has to stay readable after somebody leaves.
 *
 * **Nothing here is generated by us.** The number comes from the portal and
 * is only recorded; its 18-character shape is checked and nothing more.
 */

/** The shape the ICAI issues: 18 letters and digits. */
export const UDIN_PATTERN = /^[0-9A-Z]{18}$/;

const udinSchema = new mongoose.Schema(
  {
    udin: {
      type: String,
      required: true,
      uppercase: true,
      trim: true,
      match: [UDIN_PATTERN, "A UDIN is 18 letters and digits"],
    },

    clientId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Client",
      required: true,
    },
    /** Absent for a certificate issued outside any engagement. */
    engagementId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Engagement",
      default: null,
    },
    branchId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Branch",
      required: true,
    },

    /** The member whose membership the UDIN was generated against. */
    memberId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },
    /** Their membership number as it was then, so the row survives them. */
    membershipNo: { type: String, trim: true, default: "" },

    /**
     * What was signed, in the firm's own words. The ICAI's own document
     * categories are deliberately not modelled: they change, and inventing
     * a list of them would be the kind of guess CLAUDE.md rule 8 forbids.
     */
    documentType: { type: String, required: true, trim: true, maxlength: 120 },
    generatedOn: { type: Date, required: true },

    /**
     * A UDIN can be revoked on the portal. It is never deleted here — the
     * number existed and the register says what became of it.
     */
    revokedAt: { type: Date, default: null },
    revokeReason: { type: String, trim: true, default: "" },

    note: { type: String, trim: true, default: "", maxlength: 500 },

    createdBy: { type: String, default: null },
    updatedBy: { type: String, default: null },
  },
  { timestamps: true },
);

udinSchema.plugin(softDeletePlugin);
udinSchema.plugin(auditPlugin, { entityType: "Udin" });

/**
 * One number, one row. The unique index is what makes the duplicate check
 * safe when two people save at the same moment — the second save loses at
 * the database rather than both appearing to succeed.
 */
udinSchema.index(
  { udin: 1 },
  { unique: true, partialFilterExpression: { deletedAt: null } },
);
udinSchema.index({ clientId: 1, generatedOn: -1 });
udinSchema.index({ engagementId: 1 });
udinSchema.index({ branchId: 1, generatedOn: -1 });

export default mongoose.models.Udin ?? mongoose.model("Udin", udinSchema);
