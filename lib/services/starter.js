/**
 * The starter catalog from the table in spec section 4.
 *
 * The firm edits all of this in Settings -> Services; it is a first draft, not
 * a rule. Two things are deliberately left blank for the owner to fill in:
 *
 *  - **Fees.** Every service is seeded at zero. The firm's prices are not in
 *    the spec and are not ours to invent.
 *  - **SAC codes.** Only 998221 is named in the spec, so only the audit
 *    services carry it. The rest are blank, and the catalog screen says so,
 *    because a wrong SAC code goes onto a GST invoice.
 *
 * Where the spec's turnaround column says "before the due date" rather than a
 * number of days, `turnaroundDays` is null and the sentence is kept in
 * `turnaroundNote`. The real rule arrives with the due-date master in Step 7 —
 * no statutory date is invented here (CLAUDE.md rule 8).
 */

