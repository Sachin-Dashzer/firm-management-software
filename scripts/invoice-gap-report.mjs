/**
 * Explain every missing number in every invoice series.
 * `npm run invoice:gaps`
 *
 * **Read-only, and it never renumbers anything.** A GST series is not
 * tidied up: a gap is evidence, and the right response to one is an
 * explanation on file, not a different set of numbers. Rule 3 of the
 * go-live brief, and it is also the law — an issued invoice number is
 * spent whatever happens to the invoice afterwards.
 *
 * The readiness audit found gaps in three series and could not say why from
 * the invoices alone, because the invoices that had taken those numbers
 * were gone. The audit log still had them: it records every issue, and it
 * is a hash chain, so it cannot have been quietly edited. That is what this
 * cross-references.
 *
 * Writes `docs/INVOICE_GAPS.md` — the note a CA keeps on file and hands to
 * an auditor who asks.
 */

import { writeFileSync } from "node:fs";
import mongoose from "mongoose";
import { findGaps } from "../lib/billing/number.js";
import { formatISTDate } from "../lib/dates.js";

const OUT = new URL("../docs/INVOICE_GAPS.md", import.meta.url);

async function main() {
  if (!process.env.MONGODB_URI) {
    console.error("\n  MONGODB_URI is not set. Run through `npm run invoice:gaps`.\n");
    process.exit(1);
  }

  await mongoose.connect(process.env.MONGODB_URI);
  const db = mongoose.connection.db;

  /*
   * Soft-deleted invoices count as present: they took the number and the
   * record still exists, so that is not a gap. `withDeleted` is not
   * available on the raw driver, which is exactly why the raw driver is
   * used here — the default scope would hide them and invent gaps.
   */
  const invoices = await db
    .collection("invoices")
    .find({ number: { $ne: null } })
    .project({ number: 1, seq: 1, series: 1, status: 1, deletedAt: 1, createdAt: 1 })
    .toArray();

  const counters = await db
    .collection("counters")
    .find({ _id: { $regex: "/" } })
    .toArray();

  /** Every `invoice_issue` the audit log ever recorded, by the number in its note. */
  const issued = new Map();
  for (const row of await db
    .collection("auditlogs")
    .find({ action: "invoice_issue" })
    .sort({ seq: 1 })
    .toArray()) {
    const match = /([A-Z]{3}\/\d{2}-\d{2})\/(\d{4})/.exec(row.note ?? "");
    if (!match) continue;
    issued.set(`${match[1]}/${match[2]}`, row);
  }

  /** @type {Map<string, number[]>} */
  const bySeries = new Map();
  for (const invoice of invoices) {
    const series = invoice.series || String(invoice.number).split("/").slice(0, 2).join("/");
    if (!bySeries.has(series)) bySeries.set(series, []);
    bySeries.get(series).push(invoice.seq);
  }

  // a series whose counter has moved but which holds no invoice at all
  for (const counter of counters) {
    if (!bySeries.has(counter._id)) bySeries.set(counter._id, []);
  }

  const lines = [
    "# Missing invoice numbers, and why",
    "",
    "Generated by `npm run invoice:gaps`. Read-only: **no invoice in this",
    "system has ever been renumbered, and none will be.** An issued number is",
    "spent, and a gap in a series is evidence of something that happened — so",
    "the right answer to one is this explanation, kept on file.",
    "",
    `Written ${formatISTDate(new Date())} against \`${mongoose.connection.name}\`.`,
    "",
    "## How a gap happens here",
    "",
    "An invoice number is taken by an atomic `$inc` on a counter, inside the",
    "same transaction that writes the invoice (`lib/billing/number.js`). That",
    "is what makes the series gapless under load: two people issuing at the",
    "same moment cannot get the same number, and a transaction that rolls back",
    "gives its number back.",
    "",
    "What it does not survive is an invoice being **removed from the database**",
    "after it was issued — the counter does not wind back, because an issued",
    "number is not reusable. Every gap below is one of those, and the audit log",
    "names it: the log is a hash chain, verified intact, so an entry in it",
    "could not have been edited to say something else.",
    "",
  ];

  let totalGaps = 0;
  const unexplained = [];

  for (const [series, seqs] of [...bySeries].sort()) {
    const gaps = findGaps(seqs);
    const counter = counters.find((c) => c._id === series);
    const highest = Math.max(gaps.highest, counter?.seq ?? 0);

    // the counter may be ahead of the highest surviving invoice
    const missing = [];
    for (let n = 1; n <= highest; n += 1) {
      if (!seqs.includes(n)) missing.push(n);
    }

    lines.push(`## ${series}`);
    lines.push("");
    lines.push(
      `${seqs.length} invoice(s) on file, counter at ${counter?.seq ?? "—"}.`,
    );
    lines.push("");

    if (missing.length === 0) {
      lines.push("No gaps: every number from 1 to the counter is accounted for.");
      lines.push("");
      continue;
    }

    totalGaps += missing.length;
    lines.push("| Number | What the audit log says | When |");
    lines.push("| --- | --- | --- |");

    for (const n of missing) {
      const number = `${series}/${String(n).padStart(4, "0")}`;
      const row = issued.get(number);
      if (row) {
        lines.push(
          `| ${number} | Issued and later removed — \`${(row.note ?? "").replace(/\|/g, "\\|")}\` (audit entry #${row.seq}, by ${row.userName || "System"}) | ${formatISTDate(new Date(row.ts))} |`,
        );
      } else {
        unexplained.push(number);
        lines.push(
          `| ${number} | No \`invoice_issue\` entry names this number. See "Numbers with no issue entry" below. | — |`,
        );
      }
    }
    lines.push("");
  }

  lines.push("## Summary");
  lines.push("");
  lines.push(
    totalGaps === 0
      ? "No series has a gap."
      : `${totalGaps} missing number(s) across ${bySeries.size} series, ${totalGaps - unexplained.length} of them explained by an audit entry.`,
  );
  lines.push("");

  if (unexplained.length) {
    /*
     * Say what the log proves and stop there. The first version of this
     * asserted these were failed transactions, which sounded plausible and
     * was not something the data showed — and a document a CA hands to an
     * auditor is the wrong place to guess.
     */
    const created = await db
      .collection("auditlogs")
      .countDocuments({ entityType: "Invoice", action: "create" });
    const surviving = invoices.length;

    lines.push("## Numbers with no issue entry");
    lines.push("");
    lines.push(
      `${unexplained.length} number(s) have no \`invoice_issue\` entry naming them: ${unexplained.join(", ")}.`,
    );
    lines.push("");
    lines.push(
      `What the log does show, firm-wide: **${created} invoice records were ` +
        `created and ${surviving} still carry a number.** ` +
        "Not every path that takes a number writes an `invoice_issue` entry — " +
        "the sample seeder (`scripts/sample.js`) issues through the same counter " +
        "inside a transaction but records the save rather than an issue — so an " +
        "invoice seeded and later cleared away leaves a spent number and no " +
        "issue entry. That matches the counts above.",
    );
    lines.push("");
    lines.push(
      "The other way to reach this state is a transaction that takes a number",
      "and then fails before writing the invoice. That is designed behaviour —",
      "the alternative is reusing a number — but it is worth knowing which you",
      "are looking at. If numbers start appearing here during ordinary work,",
      "rather than only in series created while testing, the invoice screen is",
      "failing at its last step and that needs reading.",
    );
    lines.push("");
  }

  lines.push(
    "If this database has been used for testing, expect gaps in series whose",
    "prefix you do not recognise, and in real series from before the firm",
    "started relying on the system. Both are explained above rather than",
    "hidden.",
    "",
  );

  const text = lines.join("\n");
  writeFileSync(OUT, text);

  console.log(`\n  ${totalGaps} missing number(s) across ${bySeries.size} series.`);
  if (unexplained.length) {
    console.log(`  ${unexplained.length} not explained by the audit log.`);
  }
  console.log(`  Written to docs/INVOICE_GAPS.md\n`);

  await mongoose.disconnect();
}

main().catch(async (error) => {
  console.error(`\n  ${error.message}\n`);
  await mongoose.disconnect().catch(() => {});
  process.exit(1);
});
